# Подписка: загрузка и вывод ключей построчно.

# ── подписка ───────────────────────────────────────────────────────────────
# Подписка -- обычный https-адрес со списком ключей, не ключ. Подписки
# обычно base64 (и base64url), а на роутере нет ни base64, ни openssl
# (busybox, проверено 2026-09-03): раскодирует ucode ниже, а не раскодированное
# отдаётся как есть -- панель раскодирует сама (atob), если в ответе нет «://».
# Сначала через прокси byway: домен подписки может лежать в списке, и
# напрямую роутер до него не достанет.
cmd_sub() {
    _u=$1
    [ -n "$_u" ] || die "byway sub <адрес подписки>"
    case "$_u" in
      https://*) ;;
      # Открытый HTTP читается и правится на лету: подложенный ключ выиграл бы
      # по задержке, и туннель пошёл бы через чужой сервер.
      http://*) die "подписка по http:// не принимается: ключи в ней может подменить кто угодно на пути — нужен https://" ;;
      *) die "это не адрес подписки: ожидается https://" ;;
    esac

    # Подкоманда доступна держателю роли панели (ACL: `byway sub *`), а curl
    # идёт от root: петля и приватные диапазоны отсекаются
    # до запроса. Имя разрешается здесь и проверяется результат (имя на
    # 127.0.0.1 прошло бы по букве). Редирект во внутренний диапазон не закрыт:
    # число редиректов ограничено, граница -- exec в acl.json.
    # IPv6-литерал защита ниже не разбирает: [::1] прошёл бы как «имя».
    case "$_u" in
      *://\[*|*@\[*) die "адрес подписки с IPv6-литералом не поддерживается — нужно имя или IPv4" ;;
    esac
    _sh=${_u#*://}; _sh=${_sh%%/*}; _sh=${_sh%%\?*}
    _sh=${_sh##*@}; _sh=${_sh%%:*}
    case "$_sh" in
      localhost|localhost.*|*.localhost) die "адрес подписки указывает на сам роутер" ;;
    esac
    _sip=$_sh
    case "$_sh" in
      *[a-zA-Z]*) _sip=$(a_of "$_sh") ;;
    esac
    case "${_sip:-0.0.0.0}" in
      127.*|0.*|10.*|192.168.*|169.254.*|198.18.*|198.19.*|\
      172.1[6-9].*|172.2[0-9].*|172.3[01].*)
        dief "адрес подписки ведёт внутрь сети (%s) — byway туда не ходит" "${_sip:-?}" ;;
    esac

    _px=$(u local_proxy_port); _px=${_px:-1603}
    # Адрес (секрет) -- конфигом со стандартного ввода, а не аргументом: аргумент
    # виден всем в /proc/*/cmdline.
    _uq=$(printf '%s' "$_u" | sed 's/[\\"]/\\&/g')
    _raw=$(printf 'url = "%s"\n' "$_uq" | curl -fsSL --max-time 25 --max-filesize 4194304 --max-redirs 3 -A "Mozilla/5.0" \
           --proxy "http://127.0.0.1:$_px" --config - 2>/dev/null || true)
    if [ -z "$_raw" ]; then
        _raw=$(printf 'url = "%s"\n' "$_uq" | curl -fsSL --max-time 25 --max-filesize 4194304 --max-redirs 3 -A "Mozilla/5.0" --config - 2>/dev/null || true)
    fi
    [ -n "$_raw" ] || die "подписка не скачалась: стоит проверить адрес и связь"
    # Подписка почти всегда в base64 (и base64url): раскодирует ucode. Не
    # раскодировалась в ключи -- отдаём как есть; панель раскодирует сама,
    # только если «://» в ответе нет.
    case "$_raw" in
      *://*) ;;
      *) _dec=$(printf '%s' "$_raw" | ucode -S -e '
              let fs = require("fs");
              let s = replace(fs.stdin.read("all") ?? "", /[\r\n\t ]/g, "");
              s = replace(replace(s, "_", "/"), "-", "+");
              if (length(s) % 4 == 2) s += "==";
              else if (length(s) % 4 == 3) s += "=";
              print(b64dec(s) ?? "");' 2>/dev/null || true)
         case "$_dec" in *://*) _raw=$_dec ;; esac ;;
    esac
    printf '%s\n' "$_raw"
}
