# Общее для всех модулей: вывод и журнал, чтение UCI (u), перевод (_t, _f),
# проверка значений (val_or, port_ok), замки, сравнение версий. Единственный
# модуль, где код исполняется при загрузке: язык и жалоба на путь к ядру.

_say()  { printf '\033[1;32m[*]\033[0m %s\n' "$1"; }
_warn() { printf '\033[1;33m[!]\033[0m %s\n' "$1"; }
die_raw() { printf '\033[1;31m[x]\033[0m %s\n' "$1"; exit 1; }

# Вторые (sayf, warnf, dief) переводят ФОРМАТ, а не готовый текст:
# подставленное значение в словаре не найдётся, и строка осталась бы русской.
say()   { _say  "$(_t "$1")"; }
warn()  { _warn "$(_t "$1")"; }
die()   { die_raw "$(_t "$1")"; }
sayf()  { _fmt=$(_t "$1"); shift; _say    "$(printf "$_fmt" "$@")"; }
warnf() { _fmt=$(_t "$1"); shift; _warn   "$(printf "$_fmt" "$@")"; }
dief()  { _fmt=$(_t "$1"); shift; die_raw "$(printf "$_fmt" "$@")"; }

# Журнал системы читает тот же человек, что и экран; обёртки не дают забыть
# перевод строк logger.
logt()  { logger -t byway "$(_t "$1")"; }
logf()  { _lfm=$(_t "$1"); shift; logger -t byway "$(printf "$_lfm" "$@")"; }

# || true структурный: uci -q get на незаданной опции даёт 1, и VAR=$(u x) под
# set -e молча убивает скрипт. Закрыто здесь для всех опций сразу.
u() { uci -q get "byway.main.$1" || true; }

# ── язык вывода ────────────────────────────────────────────────────────────
# Русские строки в коде -- ключ; перевод -- файл «ключ<TAB>перевод» на язык.
# Язык добавляется без правки кода, пропущенная строка остаётся русской, а не
# пустой. gettext не годится: его нет в busybox, панели нужен был бы пакет.
BW_LANG=$(u lang); BW_LANG=${BW_LANG:-ru}
LANGDIR=$LISTS/lang
TAB=$(printf '\t')

_t() {
    [ "$BW_LANG" = "ru" ] && { printf '%s' "$1"; return 0; }
    _tf=$LANGDIR/$BW_LANG.tsv
    [ -f "$_tf" ] || { printf '%s' "$1"; return 0; }
    # index()==1, а не grep -F: тот ищет подстроку где угодно, и короткий ключ
    # совпадал внутри длинного. Ключ -- в начале строки, до табуляции.
    # Ключ через ENVIRON, не -v: -v разворачивает escape-последовательности, и
    # ключи с переводом строки не находились.
    _tv=$(BW_K="$1$TAB" awk 'index($0, ENVIRON["BW_K"]) == 1 { print substr($0, length(ENVIRON["BW_K"]) + 1); exit }' "$_tf" 2>/dev/null || true)
    printf '%s' "${_tv:-$1}"
}

