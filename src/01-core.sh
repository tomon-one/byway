# Порт: число 1..65535; идёт в JSON без кавычек (порт ключа и входы).
port_ok() {
    case "$1" in
        ''|*[!0-9]*) return 1 ;;
    esac
    [ "$1" -ge 1 ] && [ "$1" -le 65535 ]
}

# grep -c на нуле печатает 0 и возвращает 1: `|| echo 0` давал два нуля.
count_list() {
    [ -f "$1" ] || { echo 0; return 0; }
    awk '{ gsub(/^[[:space:]]+|[[:space:]\r]+$/, "")
           if ($0 == "") next
           if (substr($0, 1, 1) == "#") next
           if (substr($0, 1, 2) == "//") next
           n++ } END { print n + 0 }' "$1"
}

# Живость движка -- по pid-файлу procd, не по разбору `ps`: на procps-ng формат
# другой, и сторож считал живой движок мёртвым и снимал обвязку. /proc
# подтверждает, что это наш Xray, а не повторно выданный номер.
xray_pid() {
    _xp=$(cat /var/run/byway.pid 2>/dev/null || true)
    if [ -n "$_xp" ] && [ -r "/proc/$_xp/cmdline" ] &&
       tr '\0' ' ' < "/proc/$_xp/cmdline" 2>/dev/null | grep -q "run -c $OUT"; then
        printf '%s' "$_xp"
        return 0
    fi
    # Запасной путь: движок запущен руками, мимо службы.
    ps w 2>/dev/null | grep "run -c $OUT" | grep -v grep | awk '{print $1}' | head -1
}

# ── проверка окружения ─────────────────────────────────────────────────────
# _f -- формат с подстановками там, где перевод нужен, а обёртки say нет.
# Двойной перевод безвреден: готовая строка в словаре не найдётся.
_f() { _fm=$(_t "$1"); shift; printf "$_fm" "$@"; }

# Граница слова -- класс пробелов, не пробел: списки ключей записаны в
# несколько строк, и слово в конце строки стоит перед переводом строки.
in_set() { case " $2 " in *[[:space:]]"$1"[[:space:]]*) return 0 ;; esac; return 1; }

# ── обновления ─────────────────────────────────────────────────────────────
# Проверка только по запросу: регулярный стук в GitHub с домашнего адреса --
# заметный провайдеру след «здесь byway». Ходим через свой прокси-вход:
# github.com часто в списке, а правила в prerouting трафик самого роутера не
# ловят -- резолвер отдаёт адрес пула без маршрута, ответ -- пустота.

# Сравнение версий вида 1.2.3; sort -V в busybox нет.
ver_gt() {
    _va=$(printf '%s' "$1" | tr -c '0-9' ' ')
    _vb=$(printf '%s' "$2" | tr -c '0-9' ' ')
    # shellcheck disable=SC2086
    set -- $_va; _a1=${1:-0}; _a2=${2:-0}; _a3=${3:-0}
    # shellcheck disable=SC2086
    set -- $_vb; _b1=${1:-0}; _b2=${2:-0}; _b3=${3:-0}
    [ "$_a1" -ne "$_b1" ] && { [ "$_a1" -gt "$_b1" ]; return $?; }
    [ "$_a2" -ne "$_b2" ] && { [ "$_a2" -gt "$_b2" ]; return $?; }
    [ "$_a3" -gt "$_b3" ]
}

