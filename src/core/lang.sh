# Перевод: язык из UCI, словарь lang/<язык>.tsv, _t и _f. Здесь же
# отложенная жалоба на путь к ядру -- после словаря, чтобы её перевести.

# ── язык вывода ────────────────────────────────────────────────────────────
# Русские строки в коде -- ключ; перевод -- файл «ключ<TAB>перевод» на язык.
# Язык добавляется без правки кода, пропущенная строка остаётся русской, а не
# пустой. gettext не годится: его нет в busybox, панели нужен был бы пакет.
BW_LANG=$(u lang)
# Только две строчные буквы: из значения строится путь к словарю, а строки
# словаря становятся форматами printf. Опцию пишут и панель, и импорт.
case "$BW_LANG" in [a-z][a-z]) ;; *) BW_LANG=ru ;; esac

LANGDIR=$LISTS/lang

TAB=$(printf '\t')

_t() {
    [ "$BW_LANG" = "ru" ] && { printf '%s' "$1"; return 0; }
    _tf=$LANGDIR/$BW_LANG.tsv
    [ -f "$_tf" ] || { printf '%s' "$1"; return 0; }
    # index()==1, а не grep -F: тот ищет подстроку где угодно, и короткий ключ
    # совпадал внутри длинного. Ключ -- в начале строки, до табуляции.
    # Ключ через ENVIRON, не -v: -v разворачивает escape-последовательности, и
    # ключи с переводом строки не находились.
    _tv=$(BW_K="$1$TAB" awk 'index($0, ENVIRON["BW_K"]) == 1 { print substr($0, length(ENVIRON["BW_K"]) + 1); exit }' "$_tf" 2>/dev/null || true)
    printf '%s' "${_tv:-$1}"
}

# Отложенная жалоба из 00-head.sh: теперь словарь есть.
if [ -n "$XRAY_REJECTED" ]; then
    warnf "путь к движку отклонён: %s" "$XRAY_REJECTED" >&2
fi

# ── проверка окружения ─────────────────────────────────────────────────────
# _f -- формат с подстановками там, где перевод нужен, а обёртки say нет.
# Двойной перевод безвреден: готовая строка в словаре не найдётся.
_f() { _fm=$(_t "$1"); shift; printf "$_fm" "$@"; }
