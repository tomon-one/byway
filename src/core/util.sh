# Общие помощники: проверка значений, замки, сравнение версий, pid движка.

# Живость движка -- по pid-файлу procd, не по разбору `ps`: на procps-ng формат
# другой, и сторож считал живой движок мёртвым и снимал обвязку. /proc
# подтверждает, что это наш Xray, а не повторно выданный номер.
xray_pid() {
    _xp=$(cat /var/run/byway.pid 2>/dev/null || true)
    # Не от root движок идёт через ujail: в pid-файле обёртка, Xray -- потомок.
    [ "$(readlink "/proc/$_xp/exe" 2>/dev/null)" = /sbin/ujail ] &&
        _xp=$(pgrep -P "$_xp" 2>/dev/null | head -1)
    if [ -n "$_xp" ] && [ -r "/proc/$_xp/cmdline" ] &&
       tr '\0' ' ' < "/proc/$_xp/cmdline" 2>/dev/null | grep -q "run -c $OUT"; then
        printf '%s' "$_xp"
        return 0
    fi
    # Запасной путь: движок запущен руками, мимо службы.
    ps w 2>/dev/null | grep "run -c $OUT" | grep -v grep | awk '{print $1}' | head -1
}

