# Проверка только по запросу: регулярный стук в GitHub с домашнего адреса --
# заметный провайдеру след «здесь byway». Ходим через свой прокси-вход:
# github.com часто в списке, а правила в prerouting трафик самого роутера не
# ловят -- резолвер отдаёт адрес пула без маршрута, ответ -- пустота.

# Домен для проверки «трафик проходит»: заворачивается всегда, мимо списков.
PROBE_DOMAIN=example.com

# Замок на каталоге: mkdir атомарен. Живость решает pid внутри, не сам каталог:
# он остаётся от прерванного прогона, и каждый вызов ждал бы 30 с и отказал.
# Общий для сборки и обвязки (хозяев пятеро: старт, цикл попыток, reload, cron,
# человек). Замки в /var/run (root 755), не в /tmp (1777): чужой процесс
# (dnsmasq) занял бы замок с живым pid, и обвязка не поднялась бы никогда.
# Чужой замок (нет метки byway внутри) снимаем силой; владельца судим по
# файлу, а не по правам каталога: busybox stat есть не везде.
take_lock() {   # путь замка, о чём говорить человеку
    if ! mkdir "$1" 2>/dev/null; then
        _lp=$(cat "$1/pid" 2>/dev/null || true)
        # Хозяин только что сделал mkdir и ещё не записал метку и pid: в эту
        # долю секунды замок неотличим от чужого и от брошенного, и второй
        # претендент снимал его силой. Секунда на перечитывание.
        if [ ! -f "$1/byway" ] || [ -z "$_lp" ]; then
            sleep 1
            _lp=$(cat "$1/pid" 2>/dev/null || true)
        fi
        # Замок без нашей метки -- чужой. Не ждём: он может не уйти никогда, а
        # цена ожидания -- дом без резолвера.
        if [ ! -f "$1/byway" ]; then
            warnf "замок «%s» поставлен не byway -- снят принудительно" "$2"
            rm -rf "$1" 2>/dev/null || true
            mkdir "$1" 2>/dev/null || return 1
            : > "$1/byway" 2>/dev/null || true
            echo $$ > "$1/pid" 2>/dev/null || true
            return 0
        fi
        if [ -z "$_lp" ] || [ ! -d "/proc/$_lp" ]; then
            warnf "замок «%s» остался от прерванного прогона -- снят" "$2"
            rm -rf "$1" 2>/dev/null || true
            mkdir "$1" 2>/dev/null || return 1
        else
            warnf "%s уже идёт -- ожидание" "$2"
            _w=0
            while [ -d "$1" ] && [ "$_w" -lt 30 ]; do sleep 1; _w=$((_w + 1)); done
            mkdir "$1" 2>/dev/null || return 1
        fi
    fi
    : > "$1/byway" 2>/dev/null || true
    echo $$ > "$1/pid" 2>/dev/null || true
    return 0
}

