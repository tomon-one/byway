# Замок на каталоге: mkdir атомарен. Живость решает pid внутри, не сам каталог:
# он остаётся от прерванного прогона, и каждый вызов ждал бы 30 с и отказал.
# Общий для сборки и обвязки (хозяев пятеро: старт, цикл попыток, reload, cron,
# человек). Замки в /var/run (root 755), не в /tmp (1777): чужой процесс
# (dnsmasq) занял бы замок с живым pid, и обвязка не поднялась бы никогда.
# Чужой замок (нет метки byway внутри) старше двух секунд снимаем силой;
# владельца судим по файлу, а не по правам каталога: busybox stat есть не
# везде.
# Брошен ли замок: pid есть, а процесса нет; либо нет pid или метки byway, а
# каталогу больше двух секунд -- хозяин делает mkdir и сразу пишет метку и
# pid, и в эти доли секунды «пустой» замок прежде снимался как брошенный
# (Ф9, п2-1, прогон 5). Метка и pid обновляют mtime каталога.
lock_stale() {   # каталог замка, прочитанный pid
    if [ -f "$1/byway" ] && [ -n "$2" ]; then
        [ ! -d "/proc/$2" ]
        return
    fi
    _lm=$(date -r "$1" +%s 2>/dev/null) || return 1
    [ $(( $(date +%s) - _lm )) -gt 2 ]
}

take_lock() {   # путь замка, о чём говорить человеку
    _w=0
    while ! mkdir "$1" 2>/dev/null; do
        _lp=$(cat "$1/pid" 2>/dev/null || true)
        # Брошенный -- переименованием: rename удаётся одному. Переименованный
        # судим заново: между проверкой и mv замок мог смениться свежим чужим
        # -- тогда он возвращается на место, а мы ждём, как живого.
        if [ -d "$1" ] && lock_stale "$1" "$_lp" && mv "$1" "$1.gone.$$" 2>/dev/null; then
            if lock_stale "$1.gone.$$" "$(cat "$1.gone.$$/pid" 2>/dev/null || true)"; then
                if [ -f "$1.gone.$$/byway" ]; then
                    warnf "замок «%s» остался от прерванного прогона -- снят" "$2"
                else
                    warnf "замок «%s» поставлен не byway -- снят принудительно" "$2"
                fi
                rm -rf "$1.gone.$$" 2>/dev/null || true
                continue
            fi
            [ -e "$1" ] || mv "$1.gone.$$" "$1" 2>/dev/null || rm -rf "$1.gone.$$" 2>/dev/null || true
        fi
        [ "$_w" -lt 30 ] || return 1
        [ "$_w" = 0 ] && warnf "%s уже идёт -- ожидание" "$2"
        sleep 1; _w=$((_w + 1))
    done
    : > "$1/byway" 2>/dev/null || true
    echo $$ > "$1/pid" 2>/dev/null || true
    return 0
}

