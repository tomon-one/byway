# Адреса и метка для сторожа и проверок: DNS-вход, пул fakeip, метка обвязки.

# Адрес DNS-входа с умолчанием: поле в панели можно очистить, а голое `u
# dns_listen` тогда пусто -- сторож каждые 5 минут пересобирает обвязку, а
# dns_down не возвращает резолвер провайдеру.
dns_addr() {
    _da=$(u dns_listen)
    printf '%s' "${_da:-127.0.0.42}"
}

# Годится ли пул по смыслу, а не только по форме. Пул в приватном диапазоне
# мёртв молча: цепочка nft отсекает приватное первым правилом, блокировка Xray
# его перечисляет, rebind_protection dnsmasq вырезает его из ответов, а проба
# plumb on спрашивает движок напрямую и проходит. Пул уже списка -- выдача идёт
# по кругу, и соединение уходит на чужой домен.
pool_sane() {   # 1 -- пул вида a.b.c.d/len
    _pn=${1%/*}; _pl=${1#*/}
    case "$_pl" in ''|*[!0-9]*) warn "пул $1 без длины маски -- взято умолчание" >&2; return 1 ;; esac
    if [ "$_pl" -lt 8 ] || [ "$_pl" -gt 30 ]; then
        warnf "пул %s: маска /%s не годится -- взято умолчание" "$1" "$_pl" >&2
        return 1
    fi
    # Сравнение по первому октету (172, 169, 192, 100 -- по второму): опасные
    # диапазоны выровнены по октету.
    _o1=${_pn%%.*}; _r=${_pn#*.}; _o2=${_r%%.*}
    # 240.0.0.0/4 -- весь диапазон 240-255, а не края. Список тот же, что в
    # RESERVED и в правиле блокировки движка: править все три вместе.
    case "$_o1" in
      0|10|127|22[4-9]|23[0-9]|24[0-9]|25[0-5])
        warnf "пул %s лежит в приватном или зарезервированном -- он мёртв: цепочка nft отсекает такие адреса первым же правилом" "$1" >&2
        return 1 ;;
      172) [ "$_o2" -ge 16 ] && [ "$_o2" -le 31 ] && {
             warnf "пул %s лежит в 172.16/12 -- он мёртв" "$1" >&2; return 1; } ;;
      192) [ "$_o2" = 168 ] && {
             warnf "пул %s лежит в 192.168/16 -- он мёртв" "$1" >&2; return 1; } ;;
      169) [ "$_o2" = 254 ] && {
             warnf "пул %s лежит в 169.254/16 -- он мёртв" "$1" >&2; return 1; } ;;
      100) [ "$_o2" -ge 64 ] && [ "$_o2" -le 127 ] && {
             warnf "пул %s лежит в 100.64/10 -- он мёртв" "$1" >&2; return 1; } ;;
    esac
    return 0
}

# Действующие пул, метка и мосты -- одно значение для конфига движка, правил
# nft, ip rule, запрета и проверок. Каждый читал своё: при негодной настройке
# движок раздавал один пул, nft ловил другой, проверки искали третий, а ip
# rule искал метку не в том виде, в каком её печатает ядро. Аргумент
# «loud» -- предупреждать о негодной настройке (сборка конфига и правил).
eff_pool() {
    if [ "${1:-}" = loud ]; then
        _ep=$(val_or fakeip_pool "$(u fakeip_pool)" '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$' 198.18.0.0/15 "$(_t 'конфига движка')")
        pool_sane "$_ep" || _ep=198.18.0.0/15
    else
        _ep=$(val_or fakeip_pool "$(u fakeip_pool)" '^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$' 198.18.0.0/15 "" 2>/dev/null)
        pool_sane "$_ep" 2>/dev/null || _ep=198.18.0.0/15
    fi
    printf '%s' "$_ep"
}
eff_mark() {
    if [ "${1:-}" = loud ]; then
        _em=$(nft_val mark "$(u mark)" '^0x[0-9a-fA-F]{1,8}$' 0x100000)
    else
        _em=$(nft_val mark "$(u mark)" '^0x[0-9a-fA-F]{1,8}$' 0x100000 2>/dev/null)
    fi
    # Как печатает ip rule show: строчными, без ведущих нулей.
    printf '0x%x' "$((_em))"
}

# Образец адреса из пула -- по всему пулу, а не по двум первым октетам: пул
# шире /16 давал ложное «движок не отвечает» на трёх адресах из четырёх.
# Без якоря слева: потребитель сам ставит ^ перед адресом.
fakeip_re() {
    eff_pool | awk -F'[./]' '{
        l = $5 + 0; o[1] = $1; o[2] = $2; o[3] = $3; o[4] = $4
        full = int(l / 8); rem = l % 8; re = ""
        for (i = 1; i <= full; i++) re = re o[i] "\\."
        if (rem > 0) {
            sz = 2 ^ (8 - rem); b = int(o[full + 1] / sz) * sz; alt = ""
            for (v = b; v < b + sz; v++) alt = alt (alt == "" ? "" : "|") v
            re = re "(" alt ")" (full == 3 ? "([^0-9]|$)" : "\\.")
        }
        printf "%s", re
    }'
}
